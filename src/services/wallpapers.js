// Pick a random wallpaper
export function getRandomWallpaper(excludeId = null) {
  const filtered = excludeId 
    ? CURATED_WALLPAPERS.filter(w => w.id !== excludeId)
    : CURATED_WALLPAPERS;
  const list = filtered.length > 0 ? filtered : CURATED_WALLPAPERS;
  const index = Math.floor(Math.random() * list.length);
  return list[index];
}

// Guaranteed fast fallback wallpaper
export function getFastFallbackWallpaper(excludeId = null) {
  return getRandomWallpaper(excludeId);
}

// Preload an image URL into browser cache
export function preloadWallpaperImage(url, timeoutMs = 8000) {
  return new Promise((resolve, reject) => {
    if (!url) return reject(new Error('No URL provided'));
    
    let isSettled = false;
    const img = new Image();

    const timer = setTimeout(() => {
      if (!isSettled) {
        isSettled = true;
        img.src = '';
        reject(new Error(`Wallpaper preload timed out after ${timeoutMs}ms`));
      }
    }, timeoutMs);

    img.onload = () => {
      if (!isSettled) {
        isSettled = true;
        clearTimeout(timer);
        resolve(img);
      }
    };

    img.onerror = (err) => {
      if (!isSettled) {
        isSettled = true;
        clearTimeout(timer);
        reject(err);
      }
    };

    img.src = url;
  });
}

